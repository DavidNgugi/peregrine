/// One torrent the session holds, with the identity the port's `TorrentHandle` does not carry.
struct Held {
    id: usize,
    info_hash: InfoHash,
    handle: Arc<ManagedTorrent>,
}

/// The librqbit session behind `TorrentEngine`.
///
/// The session is `None` after `shutdown`, which is what makes every later call answer
/// `SessionClosed` without a second flag to keep in step with it.
pub struct LibrqbitEngine {
    descriptor: EngineDescriptor,
    session: Mutex<Option<Arc<Session>>>,
    held: Mutex<HashMap<u64, Held>>,
    next_handle: AtomicU64,
}

impl LibrqbitEngine {
    /// Starts a session whose default output folder is `output_folder`.
    ///
    /// # Errors
    ///
    /// `EngineError::Failed` when the session could not be started.
    pub async fn start(output_folder: PathBuf, limits: &EngineLimits) -> Result<Self, EngineError> {
        let options = SessionOptions {
            ratelimits: limits_config(limits),
            ..SessionOptions::default()
        };
        let session = Session::new_with_opts(output_folder, options)
            .await
            .map_err(|_| EngineError::Failed)?;
        let descriptor = EngineDescriptor::new(
            NonEmptyText::new("librqbit").map_err(|_| EngineError::Failed)?,
            NonEmptyText::new(librqbit::version()).map_err(|_| EngineError::Failed)?,
        );
        Ok(Self {
            descriptor,
            session: Mutex::new(Some(session)),
            held: Mutex::new(HashMap::new()),
            next_handle: AtomicU64::new(1),
        })
    }

    fn session(&self) -> Result<Arc<Session>, EngineError> {
        self.session
            .lock()
            .ok()
            .and_then(|guard| guard.clone())
            .ok_or(EngineError::SessionClosed)
    }

    fn held(&self, handle: TorrentHandle) -> Result<Held, EngineError> {
        self.held
            .lock()
            .ok()
            .and_then(|guard| {
                guard.get(&handle.get()).map(|held| Held {
                    id: held.id,
                    info_hash: held.info_hash,
                    handle: held.handle.clone(),
                })
            })
            .ok_or(EngineError::UnknownTorrent { handle })
    }

    /// Records a torrent the session returned, and answers the handle the port will name it by.
    fn remember(
        &self,
        id: usize,
        info_hash: InfoHash,
        handle: Arc<ManagedTorrent>,
    ) -> TorrentHandle {
        let number = self.next_handle.fetch_add(1, Ordering::Relaxed);
        if let Ok(mut guard) = self.held.lock() {
            guard.insert(
                number,
                Held {
                    id,
                    info_hash,
                    handle,
                },
            );
        }
        TorrentHandle::new(number)
    }
}

impl TorrentMetadataFetch for LibrqbitEngine {
    fn fetch_metadata(&self, source: &TorrentSource) -> EngineFuture<'_, FetchedMetadata> {
        let session = match self.session() {
            Ok(session) => session,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        let source = source.clone();
        Box::pin(async move {
            let list_only = AddTorrentOptions {
                list_only: true,
                ..AddTorrentOptions::default()
            };
            let response = session
                .add_torrent(add_torrent(&source), Some(list_only))
                .await
                .map_err(|_| EngineError::Failed)?;
            let list = match response {
                AddTorrentResponse::ListOnly(list) => list,
                AddTorrentResponse::Added(..) | AddTorrentResponse::AlreadyManaged(..) => {
                    return Err(EngineError::Failed);
                }
            };
            let entries: Vec<PayloadEntry> = list
                .info
                .iter_file_details()
                .map(|file| {
                    PayloadEntry::new(
                        file.filename.to_pathbuf().to_string_lossy().into_owned(),
                        file.len,
                        EntryKind::File,
                    )
                })
                .collect();
            Ok(FetchedMetadata::new(
                InfoHash::from_bytes(list.info_hash.0),
                PayloadDescription::new(entries),
            ))
        })
    }
}

impl TorrentEngine for LibrqbitEngine {
    fn descriptor(&self) -> &EngineDescriptor {
        &self.descriptor
    }

    fn add(&self, request: &AddRequest) -> EngineFuture<'_, TorrentHandle> {
        let session = match self.session() {
            Ok(session) => session,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        if request.selection().is_empty() {
            return Box::pin(async move { Err(EngineError::EmptySelection) });
        }
        let source = request.source().clone();
        let info_hash = request.info_hash();
        let selection: Vec<usize> = request.selection().indices().to_vec();
        let destination = request
            .destination()
            .as_path()
            .to_string_lossy()
            .into_owned();
        let overwrite = request.intent().verifies_existing_data();
        let this = self;
        Box::pin(async move {
            let options = AddTorrentOptions {
                only_files: Some(selection),
                output_folder: Some(destination),
                overwrite,
                ..AddTorrentOptions::default()
            };
            let response = session
                .add_torrent(add_torrent(&source), Some(options))
                .await
                .map_err(|_| EngineError::Failed)?;
            let (id, handle) = match response {
                AddTorrentResponse::Added(id, handle)
                | AddTorrentResponse::AlreadyManaged(id, handle) => (id, handle),
                AddTorrentResponse::ListOnly(_) => return Err(EngineError::Failed),
            };
            if handle.info_hash().0 != *info_hash.as_bytes() {
                let _ = session.delete(TorrentIdOrHash::Id(id), false).await;
                return Err(EngineError::IdentityMismatch);
            }
            Ok(this.remember(id, info_hash, handle))
        })
    }

    fn select(&self, handle: TorrentHandle, selection: &FileSelection) -> EngineFuture<'_, ()> {
        let session = match self.session() {
            Ok(session) => session,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        let held = match self.held(handle) {
            Ok(held) => held,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        if selection.is_empty() {
            return Box::pin(async move { Err(EngineError::EmptySelection) });
        }
        let set: HashSet<usize> = selection.indices().iter().copied().collect();
        Box::pin(async move {
            session
                .update_only_files(&held.handle, &set)
                .await
                .map_err(|_| EngineError::Failed)
        })
    }

    fn stream(&self, request: &StreamRequest) -> EngineFuture<'_, Box<dyn TorrentStream>> {
        let held = match self.held(request.handle()) {
            Ok(held) => held,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        let file = request.file();
        let from = request.from().get();
        Box::pin(async move {
            let count = held
                .handle
                .with_metadata(|metadata| metadata.file_infos.len())
                .map_err(|_| EngineError::Failed)?;
            if file >= count {
                return Err(EngineError::UnknownFile { index: file });
            }
            if let Some(selected) = held.handle.only_files()
                && !selected.contains(&file)
            {
                return Err(EngineError::FileNotSelected { index: file });
            }
            let mut stream = held
                .handle
                .clone()
                .stream(file)
                .await
                .map_err(|_| EngineError::Failed)?;
            let len = stream.len();
            if from > len {
                return Err(EngineError::OffsetPastEnd {
                    offset: Bytes::new(from),
                    len: Bytes::new(len),
                });
            }
            if from > 0 {
                stream
                    .seek(SeekFrom::Start(from))
                    .await
                    .map_err(|_| EngineError::Failed)?;
            }
            let position = stream.position();
            let reader: Pin<Box<dyn AsyncRead + Send>> = Box::pin(stream);
            Ok(Box::new(LibrqbitStream {
                len,
                position,
                reader,
            }) as Box<dyn TorrentStream>)
        })
    }

    fn stats(&self, handle: TorrentHandle) -> EngineFuture<'_, TorrentStats> {
        let held = match self.held(handle) {
            Ok(held) => held,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        Box::pin(async move { Ok(map_stats(held.info_hash, &held.handle.stats())) })
    }

    fn state(&self, handle: TorrentHandle) -> EngineFuture<'_, EngineState> {
        match self.held(handle) {
            Ok(_) => Box::pin(async move { Ok(EngineState::new(Vec::new())) }),
            Err(error) => Box::pin(async move { Err(error) }),
        }
    }

    fn verify(&self, handle: TorrentHandle) -> EngineFuture<'_, ()> {
        match self.held(handle) {
            Ok(_) => Box::pin(async move { Err(EngineError::Failed) }),
            Err(error) => Box::pin(async move { Err(error) }),
        }
    }

    fn limits(&self) -> EngineFuture<'_, EngineLimits> {
        let session = match self.session() {
            Ok(session) => session,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        Box::pin(async move {
            let config = session.ratelimits.get_config();
            Ok(EngineLimits::new(
                config
                    .download_bps
                    .map(|rate| ByteRate::per_second(u64::from(rate.get()))),
                config
                    .upload_bps
                    .map(|rate| ByteRate::per_second(u64::from(rate.get()))),
                None,
                None,
            ))
        })
    }

    fn set_limits(&self, limits: &EngineLimits) -> EngineFuture<'_, ()> {
        let session = match self.session() {
            Ok(session) => session,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        let download = nonzero(limits.download_rate());
        let upload = nonzero(limits.upload_rate());
        Box::pin(async move {
            session.ratelimits.set_download_bps(download);
            session.ratelimits.set_upload_bps(upload);
            Ok(())
        })
    }

    fn pause(&self, handle: TorrentHandle) -> EngineFuture<'_, ()> {
        let session = match self.session() {
            Ok(session) => session,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        let held = match self.held(handle) {
            Ok(held) => held,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        Box::pin(async move {
            session
                .pause(&held.handle)
                .await
                .map_err(|_| EngineError::Failed)
        })
    }

    fn resume(&self, handle: TorrentHandle) -> EngineFuture<'_, ()> {
        let session = match self.session() {
            Ok(session) => session,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        let held = match self.held(handle) {
            Ok(held) => held,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        Box::pin(async move {
            session
                .unpause(&held.handle)
                .await
                .map_err(|_| EngineError::Failed)
        })
    }

    fn remove(&self, handle: TorrentHandle) -> EngineFuture<'_, ()> {
        let session = match self.session() {
            Ok(session) => session,
            Err(error) => return Box::pin(async move { Err(error) }),
        };
        let held = self
            .held
            .lock()
            .ok()
            .and_then(|mut guard| guard.remove(&handle.get()));
        match held {
            Some(held) => Box::pin(async move {
                session
                    .delete(TorrentIdOrHash::Id(held.id), false)
                    .await
                    .map_err(|_| EngineError::Failed)
            }),
            None => Box::pin(async move { Ok(()) }),
        }
    }

    fn shutdown(&self) -> EngineFuture<'_, ()> {
        let session = self.session.lock().ok().and_then(|mut guard| guard.take());
        if let Ok(mut guard) = self.held.lock() {
            guard.clear();
        }
        Box::pin(async move {
            drop(session);
            Ok(())
        })
    }
}

/// The reader the port sees, wrapping librqbit's `FileStream` without naming its private type.
struct LibrqbitStream {
    len: u64,
    position: u64,
    reader: Pin<Box<dyn AsyncRead + Send>>,
}

impl TorrentStream for LibrqbitStream {
    fn len(&self) -> Bytes {
        Bytes::new(self.len)
    }

    fn position(&self) -> Bytes {
        Bytes::new(self.position)
    }

    fn read(&mut self, max_bytes: NonZeroU32) -> EngineFuture<'_, StreamChunk> {
        let capacity = max_bytes.get() as usize;
        Box::pin(async move {
            let mut buffer = vec![0_u8; capacity];
            let read = self
                .reader
                .read(&mut buffer)
                .await
                .map_err(|_| EngineError::Failed)?;
            if read == 0 {
                return Ok(StreamChunk::End);
            }
            buffer.truncate(read);
            self.position = self.position.saturating_add(read as u64);
            Ok(StreamChunk::Data(buffer))
        })
    }
}

/// The source the engine is handed, as librqbit's own add input.
fn add_torrent(source: &TorrentSource) -> AddTorrent<'static> {
    match source {
        TorrentSource::Magnet(text) => AddTorrent::from_url(text.as_str().to_owned()),
        TorrentSource::TorrentFile(bytes) => AddTorrent::from_bytes(bytes.clone()),
    }
}

/// The limits config from the port's limits, ignoring what librqbit cannot apply at runtime.
fn limits_config(limits: &EngineLimits) -> LimitsConfig {
    LimitsConfig {
        download_bps: nonzero(limits.download_rate()),
        upload_bps: nonzero(limits.upload_rate()),
    }
}

fn nonzero(rate: Option<ByteRate>) -> Option<NonZeroU32> {
    rate.and_then(|rate| u32::try_from(rate.get()).ok())
        .and_then(NonZeroU32::new)
}

/// Maps librqbit's counters onto the port's, with the approximations its doc records.
fn map_stats(info_hash: InfoHash, stats: &EngineTorrentStats) -> TorrentStats {
    let live = stats.live.as_ref();
    let download_rate = live.map_or(0, |live| live.download_speed.as_bytes());
    let upload_rate = live.map_or(0, |live| live.upload_speed.as_bytes());
    let peers = live.map_or_else(PeerCounts::default, |live| {
        PeerCounts::new(live.snapshot.peer_stats.live, 0)
    });
    let remaining = stats.total_bytes.saturating_sub(stats.progress_bytes);
    let eta = if stats.finished || download_rate == 0 {
        None
    } else {
        Some(Duration::from_secs(remaining / download_rate))
    };
    TorrentStats::new(
        info_hash,
        Transfer::new(
            Bytes::new(stats.progress_bytes),
            Bytes::new(stats.uploaded_bytes),
            ByteRate::per_second(download_rate),
            ByteRate::per_second(upload_rate),
        ),
        Bytes::new(stats.total_bytes),
        peers,
        eta,
        health(stats, download_rate),
    )
}

fn health(stats: &EngineTorrentStats, download_rate: u64) -> TorrentHealth {
    match stats.state {
        TorrentStatsState::Live => {
            let peers = stats
                .live
                .as_ref()
                .map_or(0, |live| live.snapshot.peer_stats.live);
            if peers == 0 {
                TorrentHealth::NoPeers
            } else if stats.finished || download_rate > 0 {
                TorrentHealth::Progressing
            } else {
                TorrentHealth::Stalled
            }
        }
        TorrentStatsState::Initializing { .. } => TorrentHealth::Progressing,
        TorrentStatsState::Paused | TorrentStatsState::Error => TorrentHealth::Stalled,
    }
}
