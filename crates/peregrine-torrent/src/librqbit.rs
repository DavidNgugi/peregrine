//! The librqbit `TorrentEngine` adapter (PG-E10-02) and the metadata-only fetch (PG-E10-03).
//!
//! # The librqbit 9.0.1 API this file is written against, and where each item lives
//!
//! Verified from the crate source Cargo fetched (`librqbit-9.0.1/`), never from memory:
//!
//! - `Session`, `SessionOptions`, `SessionOptions: Default` — `src/session.rs:107, 418, 484`.
//! - `Session::new_with_opts(PathBuf, SessionOptions) -> BoxFuture<anyhow::Result<Arc<Session>>>`
//!   — `src/session.rs:568`. `Session::add_torrent(&Arc<Self>, AddTorrent, Option<AddTorrentOptions>)`
//!   — `src/session.rs:1087`. `Session::{pause, unpause, delete, update_only_files}`
//!   — `src/session.rs:1604, 1610, 1423, 1617`.
//! - `AddTorrent::{from_url, from_bytes}`, `AddTorrentOptions`, `AddTorrentResponse`
//!   — `src/session.rs:337, 244, 306`. The options this file sets (`list_only`, `only_files`,
//!   `output_folder`, `overwrite`) are all fields of that struct — `src/session.rs:244`.
//! - `ManagedTorrentHandle = Arc<ManagedTorrent>` — `src/torrent_state/mod.rs:649`;
//!   `ManagedTorrent::{stream, stats, only_files, with_metadata, info_hash}`
//!   — `src/torrent_state/mod.rs:337, 503, 252, 239, 248`.
//! - The reader `stream` answers is a `FileStream`, an `AsyncRead + AsyncSeek` with `len()` and
//!   `position()` — `src/torrent_state/streaming.rs:133, 380, 398`. Its module is private, so
//!   this file never names the type: it seeks it, reads `len`/`position`, and coerces the value to
//!   `Pin<Box<dyn AsyncRead + Send>>`.
//! - `TorrentStats { state, progress_bytes, uploaded_bytes, total_bytes, finished, live }`
//!   — `src/torrent_state/stats.rs:71`; `LiveStats { download_speed, upload_speed, snapshot }`
//!   and `Speed::as_bytes` — `src/torrent_state/stats.rs:8, 234`; `AggregatePeerStats.live` is
//!   generated by `gen_stats!` (`src/stat_gen.rs:50`) from `live/peers/stats/mod.rs:12`.
//! - `Limits::{get_config, set_download_bps, set_upload_bps}` and `LimitsConfig`
//!   — `src/limits.rs:9, 77, 81, 93`.
//! - `Id20 = Id<20>(pub [u8; 20])` — `librqbit-core-9.0.1/src/hash_id.rs:8, 180`; the info-hash
//!   bytes this file copies out are that public field.
//!
//! # What librqbit 9.0.1 cannot do, and what this adapter does instead
//!
//! - **`verify` (re-check a torrent the session already holds).** The only check is
//!   `TorrentStateInitializing::check`, on a `pub(crate)` type reachable only while a torrent is
//!   initializing (`src/torrent_state/initializing.rs:30, 189`). There is no public on-demand
//!   recheck, so `verify` answers `EngineError::Failed` rather than claiming to have checked.
//! - **`StreamRequest::window` (byte read-ahead).** librqbit raises piece priority from the file
//!   ids that have an open stream (`torrent_state/streaming.rs`) but exposes no window in bytes.
//!   The window is accepted and ignored.
//! - **`EngineLimits::{connections, active_downloads}`.** `Limits`/`LimitsConfig` carry only
//!   upload/download bytes per second (`src/limits.rs:9`), peer limits are per-add, and neither
//!   has a runtime setter. `limits` answers `None` for both and `set_limits` ignores them.
//! - **`AddRequest::sequential`.** `AddTorrentOptions` has no sequential switch. It is read and
//!   ignored; librqbit downloads a file a reader has open in order.
//! - **`EngineError::UnknownFile`.** The `only_files` selection is validated inside
//!   `add_torrent`/`update_only_files` (`src/session.rs:1279, 621`), which answer an opaque error;
//!   an index past the file list therefore reaches the caller as `EngineError::Failed` rather than
//!   as `UnknownFile`.
//! - **`PeerCounts::seeds`.** `AggregatePeerStats` counts `live`, `seen`, `dead`, and others,
//!   but not seeds, so the adapter answers 0 rather than inventing one.
//! - **`EngineState`.** librqbit keeps a torrent's private session bytes to itself and persists
//!   them through `SessionPersistenceConfig`. `state` answers empty — which the port documents as
//!   a real answer — and `AddIntent::Reattach` re-adds the same source with `overwrite: true`,
//!   which is what makes librqbit verify the payload already on disk.

